rows = []
for line in inventory_data.strip().split('\n'):
    parts = line.split(',')
    if len(parts) == 3:
        item_code = parts[0].strip()
        description = parts[1].strip()
        try:
            price = float(parts[2].strip())
            rows.append({"Original Item Code": item_code, "Description": description, "Price": price})
        except:
            pass

df = pd.DataFrame(rows)
df = df.drop_duplicates(subset=['Original Item Code']).sort_values(by="Price", ascending=False).head(50)

# 1. Extract the prefix (DS, DSK, DSAF, DSMX)
df["Prefix"] = df["Original Item Code"].apply(lambda x: re.match(r'^[A-Za-z]+', x).group(0) if re.match(r'^[A-Za-z]+', x) else "")

# 2. Strip the prefix to get the raw part number
df["Part No"] = df["Original Item Code"].str.replace(r'^[A-Za-z]+', '', regex=True).str.strip()

# 3. Re-order columns: Part No first, then Model (empty), then Description and Price
df.insert(1, "Model", "")
df = df[["Part No", "Model", "Description", "Price", "Original Item Code", "Prefix"]]

file_name = "Top_50_Develon_Parts_Clean.xlsx"
df.to_excel(file_name, index=False)

